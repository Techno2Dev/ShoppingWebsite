using backend.Data;
using backend.Models;
using Microsoft.AspNetCore.Authentication;
using Microsoft.AspNetCore.Authorization;
using Microsoft.EntityFrameworkCore;
using backend.Mongo;

var builder = WebApplication.CreateBuilder(args);

if (builder.Environment.IsDevelopment())
{
    // Local test keys stay outside Git and never load on Render/Production.
    builder.Configuration.AddJsonFile("appsettings.Local.json", optional: true, reloadOnChange: true);
    builder.Configuration.AddEnvironmentVariables();
    builder.Configuration.AddCommandLine(args);
}

var storeConnectionString = builder.Configuration.GetConnectionString("Store");
if (string.IsNullOrWhiteSpace(storeConnectionString))
{
    throw new InvalidOperationException("Set ConnectionStrings__Store to a PostgreSQL or MongoDB connection URI.");
}
var useMongo = storeConnectionString.StartsWith("mongodb://", StringComparison.OrdinalIgnoreCase) ||
    storeConnectionString.StartsWith("mongodb+srv://", StringComparison.OrdinalIgnoreCase);
builder.Services.AddControllers(options => options.Conventions.Add(new StoreControllerConvention(useMongo)));
if (useMongo)
    builder.Services.AddSingleton(new MongoStore(storeConnectionString));
else
{
    storeConnectionString = PostgresConnectionString.Normalize(storeConnectionString);
    builder.Services.AddDbContext<StoreDbContext>(options => options.UseNpgsql(storeConnectionString));
}
builder.Services.AddSingleton<TelegramOrderNotifier>();
builder.Services.AddHttpClient<RazorpayTestGateway>(client => client.Timeout = TimeSpan.FromSeconds(12));
var frontendOrigins = builder.Configuration.GetSection("FrontendOrigins").Get<string[]>() ??
    (builder.Configuration["FrontendOrigin"] is { Length: > 0 } configuredOrigin
        ? configuredOrigin.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
        : Array.Empty<string>());
frontendOrigins = frontendOrigins
    .Append("http://localhost:4200")
    .Append("https://shoppingwebsite-1-9ytf.onrender.com")
    .Distinct(StringComparer.OrdinalIgnoreCase)
    .ToArray();

builder.Services.AddCors(options => options.AddPolicy("frontend", policy =>
    policy.WithOrigins(frontendOrigins).AllowAnyHeader().AllowAnyMethod()));
builder.Services.AddAuthentication("AdminBearer")
    .AddScheme<AuthenticationSchemeOptions, AdminBearerAuthenticationHandler>("AdminBearer", _ => { })
    .AddScheme<AuthenticationSchemeOptions, CustomerBearerAuthenticationHandler>("CustomerBearer", _ => { });
builder.Services.AddAuthorization(options =>
{
    options.AddPolicy("AdminOnly", policy => policy.AddAuthenticationSchemes("AdminBearer")
        .RequireAuthenticatedUser().RequireRole("Admin"));
    options.AddPolicy("CustomerOnly", policy => policy.AddAuthenticationSchemes("CustomerBearer")
        .RequireAuthenticatedUser().RequireRole("Customer"));
});

var app = builder.Build();

app.UseCors("frontend");
app.UseAuthentication();
app.UseAuthorization();
app.MapControllers();

using (var scope = app.Services.CreateScope())
{
    if (useMongo)
    {
        await scope.ServiceProvider.GetRequiredService<MongoStore>().InitializeAsync(builder.Configuration, app.Environment.IsDevelopment());
    }
    else
    {
    var db = scope.ServiceProvider.GetRequiredService<StoreDbContext>();
    db.Database.EnsureCreated();
    // EnsureCreated does not add new tables to an existing database.
    db.Database.ExecuteSqlRaw("CREATE TABLE IF NOT EXISTS \"AdminSessions\" (\"TokenHash\" text PRIMARY KEY, \"AdminUserId\" integer NOT NULL REFERENCES \"AdminUsers\"(\"Id\") ON DELETE CASCADE, \"ExpiresAt\" timestamp with time zone NOT NULL);");
    db.Database.ExecuteSqlRaw("CREATE TABLE IF NOT EXISTS \"CustomerUsers\" (\"Id\" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \"GoogleSubject\" character varying(255) NOT NULL, \"Email\" character varying(254) NOT NULL, \"Name\" character varying(120) NOT NULL, \"PhotoUrl\" character varying(1000) NULL, \"DeliveryAddress\" character varying(500) NULL, \"CreatedAt\" timestamp with time zone NOT NULL);");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"CustomerUsers\" ADD COLUMN IF NOT EXISTS \"MobileNumber\" character varying(10) NULL;");
    db.Database.ExecuteSqlRaw("CREATE UNIQUE INDEX IF NOT EXISTS \"IX_CustomerUsers_GoogleSubject\" ON \"CustomerUsers\" (\"GoogleSubject\");");
    db.Database.ExecuteSqlRaw("CREATE TABLE IF NOT EXISTS \"CustomerSessions\" (\"TokenHash\" text PRIMARY KEY, \"CustomerUserId\" integer NOT NULL REFERENCES \"CustomerUsers\"(\"Id\") ON DELETE CASCADE, \"ExpiresAt\" timestamp with time zone NOT NULL);");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"CustomerUserId\" integer NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"MobileNumber\" character varying(10) NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"FulfillmentStatus\" text NOT NULL DEFAULT 'Order received';");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"TrackingId\" character varying(100) NULL;");
    db.Database.ExecuteSqlRaw("CREATE INDEX IF NOT EXISTS \"IX_Orders_CustomerUserId\" ON \"Orders\" (\"CustomerUserId\");");
    db.Database.ExecuteSqlRaw("DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'FK_Orders_CustomerUsers_CustomerUserId') THEN ALTER TABLE \"Orders\" ADD CONSTRAINT \"FK_Orders_CustomerUsers_CustomerUserId\" FOREIGN KEY (\"CustomerUserId\") REFERENCES \"CustomerUsers\"(\"Id\") ON DELETE SET NULL; END IF; END $$;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"PaymentReference\" character varying(100) NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"PaymentReportedAt\" timestamp with time zone NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"PaymentVerifiedAt\" timestamp with time zone NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"PaymentVerifiedBy\" character varying(100) NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"PaymentAccessTokenHash\" text NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"PaymentMethod\" text NOT NULL DEFAULT 'UPI';");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"RazorpayOrderId\" text NULL;");
    db.Database.ExecuteSqlRaw("ALTER TABLE \"Orders\" ADD COLUMN IF NOT EXISTS \"RazorpayPaymentId\" text NULL;");
    db.Database.ExecuteSqlRaw("CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Orders_RazorpayOrderId\" ON \"Orders\" (\"RazorpayOrderId\");");
    db.Database.ExecuteSqlRaw("CREATE UNIQUE INDEX IF NOT EXISTS \"IX_Orders_RazorpayPaymentId\" ON \"Orders\" (\"RazorpayPaymentId\");");
    db.Database.ExecuteSqlRaw("UPDATE \"Orders\" SET \"PaymentStatus\" = 'Pending' WHERE \"PaymentStatus\" = 'PaymentReported';");

    var configuredAdminUserName = builder.Configuration["Admin:UserName"];
    var configuredAdminPassword = builder.Configuration["Admin:Password"];
    if (app.Environment.IsDevelopment())
    {
        configuredAdminUserName ??= "admin";
        configuredAdminPassword ??= "KitchenKatta@123";
    }

    if (!string.IsNullOrWhiteSpace(configuredAdminUserName) &&
        !string.IsNullOrWhiteSpace(configuredAdminPassword) &&
        !db.AdminUsers.Any())
    {
        db.AdminUsers.Add(new AdminUser
        {
            UserName = configuredAdminUserName.Trim(),
            NormalizedUserName = configuredAdminUserName.Trim().ToUpperInvariant(),
            PasswordHash = PasswordHashing.Hash(configuredAdminPassword)
        });
        db.SaveChanges();
    }

    if (!db.Products.Any())
    {
        db.Products.AddRange(
            new Product { Name = "Everyday Backpack", Description = "A lightweight everyday carry with room for all the essentials.", Price = 64.00m, Image = "🎒", Category = "Accessories", Stock = 18 },
            new Product { Name = "Ceramic Pour-over Set", Description = "Slow mornings start with a better cup. Includes dripper and server.", Price = 42.00m, Image = "☕", Category = "Home", Stock = 12 },
            new Product { Name = "Studio Headphones", Description = "Rich, balanced sound in a comfortable over-ear fit.", Price = 129.00m, Image = "🎧", Category = "Tech", Stock = 9 },
            new Product { Name = "Linen Market Tote", Description = "A sturdy, reusable tote made for market runs and weekends away.", Price = 28.00m, Image = "👜", Category = "Accessories", Stock = 24 },
            new Product { Name = "Desk Plant Kit", Description = "A low-maintenance green companion, pot included.", Price = 35.00m, Image = "🪴", Category = "Home", Stock = 15 },
            new Product { Name = "Pocket Notebook Set", Description = "Three thoughtfully designed notebooks for ideas on the go.", Price = 18.00m, Image = "📓", Category = "Stationery", Stock = 30 }
        );
        db.SaveChanges();
    }
    }
}

app.Run();
